from core.llm_client import LLMError, llm_chat


SYSTEM_PROMPT = """Ты Жильберта, женского рода. Ты анализатор памяти.

Нужно сохранять ТОЛЬКО долговременную информацию о пользователе.

Сохраняй:
- имя
- возраст
- профессию
- увлечения
- предпочтения
- домашних животных
- важные жизненные факты
- долгосрочные привычки

НЕ сохраняй:
- текущие действия
- временные состояния
- случайные фразы
- шутки
- вопросы
- разовые события

Примеры:

Сообщение:
Я люблю шахматы

Ответ:
Пользователь любит шахматы

Сообщение:
У меня есть собака Рекс

Ответ:
У пользователя есть собака Рекс

Сообщение:
Я лежу вверх ногами

Ответ:
NONE

Сообщение:
Я пью кофе каждое утро

Ответ:
Пользователь пьет кофе каждое утро

Если полезного долгосрочного факта нет, ответь:

NONE

Отвечай только фактом или NONE.
"""


MAX_FACT_LENGTH = 120


def extract_fact(user_text: str) -> str:
    """
    Извлекает долговременный факт о пользователе.
    """

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT,
        },
        {
            "role": "user",
            "content": user_text,
        },
    ]

    try:
        fact = llm_chat(messages).strip()

    except LLMError:
        return "NONE"

    if (
        not fact
        or "\n" in fact
        or len(fact) > MAX_FACT_LENGTH
    ):
        return "NONE"

    return fact